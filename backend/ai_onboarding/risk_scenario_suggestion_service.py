# Step 8A is advisory-only: the response carries no ids, no write flags, and no approval
# flags. Every scenario stays at review_status 'pending_review'.
REVIEW_STATUS = "pending_review"

MAX_TITLE_LENGTH = 200

ALLOWED_SCENARIO_KEYS = {
    "temporary_id",
    "title",
    "description",
    "asset_reference",
    "asset_title",
    "linked_finding_reference",
    "linked_finding_title",
    "linked_applied_control_reference",
    "linked_applied_control_title",
    "linked_remediation_action_reference",
    "linked_remediation_action_title",
    "linked_framework_control_reference",
    "linked_framework_control_code",
    "linked_framework_control_title",
    "threat",
    "vulnerability",
    "impact_description",
    "likelihood",
    "impact",
    "risk_level",
    "rationale",
    "recommended_next_steps",
    "confidence",
    "review_status",
}

OPTIONAL_LINK_KEYS = (
    "asset_reference",
    "asset_title",
    "linked_finding_reference",
    "linked_finding_title",
    "linked_applied_control_reference",
    "linked_applied_control_title",
    "linked_remediation_action_reference",
    "linked_remediation_action_title",
    "linked_framework_control_reference",
    "linked_framework_control_code",
    "linked_framework_control_title",
)

TEXT_SCENARIO_KEYS = (
    "temporary_id",
    "title",
    "description",
    "threat",
    "vulnerability",
    "impact_description",
    "rationale",
    *OPTIONAL_LINK_KEYS,
)

ENUM_KEYS = (
    ("likelihood", LIKELIHOOD_CHOICES),
    ("impact", IMPACT_CHOICES),
    ("risk_level", RISK_LEVEL_CHOICES),
)

# Deterministic ordering used by the fallback to derive a reviewable risk level from the
# advisory likelihood/impact pair. This is a readable heuristic for human review only; it
# is never a platform risk rating and it is never written anywhere.
_SEVERITY_ORDER = ("low", "medium", "high", "critical")

IDENTITY_TOKENS = (
    "mfa",
    "multi-factor",
    "multifactor",
    "remote access",
    "privileged",
    "pam",
    "password",
    "authentication",
    "identity",
    "access",
)


class AiRiskScenarioSuggestionService:
    def __init__(self, *, base_dir: str | None = None, provider=None):
        self.base_dir = base_dir or str(Path(__file__).resolve().parents[1])
        self.provider = provider

    def build_risk_scenario_suggestion_draft(
        self, request_data: dict[str, Any]
    ) -> dict[str, Any]:
        normalized = _normalize_request_data(request_data)

        if not _has_risk_context(normalized):
            # Nothing reviewed to reason about: Step 8A refuses rather than inventing risk.
            return _finalize(_build_blocked_draft())

        provider = (
            self.provider
            if self.provider is not None
            else get_risk_scenario_suggestion_provider()
        )

        if provider is None:
            draft = build_risk_scenario_suggestion_fallback_draft(normalized)
            _annotate_provider_mode(
                draft,
                provider_mode="provider_not_configured_fallback",
                warning={
                    "code": "provider_not_configured_fallback",
                    "message": (
                        "No AI provider is configured; the advisory risk scenario draft was "
                        "generated by the deterministic fallback."
                    ),
                    "affected_fields": ["risk_scenarios"],
                    "needs_review": True,
                },
            )
        else:
            try:
                draft = provider.build_risk_scenario_suggestion_draft(normalized)
                _annotate_provider_mode(draft, provider_mode="configured_local_provider")
            except RiskScenarioSuggestionProviderError as exc:
                if not exc.allow_fallback:
                    raise
                draft = build_risk_scenario_suggestion_fallback_draft(normalized)
                _annotate_provider_mode(
                    draft,
                    provider_mode="local_provider_error_fallback",
                    warning={
                        "code": "local_provider_error_fallback",
                        "message": exc.detail,
                        "affected_fields": ["risk_scenarios"],
                        "needs_review": True,
                    },
                )

        _enrich_draft(draft)
        return _finalize(draft)


def build_risk_scenario_suggestion_draft(
    request_data: dict[str, Any],
    *,
    base_dir: str | None = None,
    provider=None,
) -> dict[str, Any]:
    service = AiRiskScenarioSuggestionService(base_dir=base_dir, provider=provider)
    return service.build_risk_scenario_suggestion_draft(request_data)


def _finalize(draft: dict[str, Any]) -> dict[str, Any]:
    validate_risk_scenario_suggestion_guardrails(draft)

    serializer = AiRiskScenarioSuggestionDraftSerializer(data=draft)
    if not serializer.is_valid():
        raise RiskScenarioSuggestionDraftValidationError(
            "ai_risk_scenario_suggestion_draft_validation_failed",
            "Generated advisory risk scenario draft did not pass contract validation.",
            serializer.errors,
        )

    validated_draft = serializer.data
    validate_risk_scenario_suggestion_guardrails(validated_draft)
    return validated_draft


def _has_risk_context(request_data: dict[str, Any]) -> bool:
    return bool(
        request_data.get("preliminary_findings")
        or request_data.get("known_weaknesses")
        or request_data.get("assets")
    )


def _build_blocked_draft() -> dict[str, Any]:
    return {
        "provider_mode": "risk_context_missing_blocked",
        "overall_confidence": 0.0,
        "risk_scenarios": [],
        "warnings": [
            {
                "code": "no_risk_input_context",
                "message": (
                    "No assets, preliminary findings, or known weaknesses were supplied, so "
                    "Step 8A produced no risk scenarios. Risk scenarios are never invented "
                    "without reviewed onboarding context."
                ),
                "affected_fields": ["assets", "preliminary_findings", "known_weaknesses"],
                "needs_review": True,
            }
        ],
        "ambiguity_flags": [
            {
                "code": "no_risk_input_context",
                "message": (
                    "Complete Steps 3A-7B, or supply assets, findings, or known weaknesses, "
                    "before Step 8A can suggest risk scenarios."
                ),
            }
        ],
    }


# ---- Deterministic fallback ----------------------------------------------------------


def build_risk_scenario_suggestion_fallback_draft(
    request_data: dict[str, Any],
) -> dict[str, Any]:
    """Deterministic advisory draft used when no local provider is available.

    It never reads or writes the database: every value is derived from the readable
    request context only, and it never invents an asset, finding, or control.
    """
    findings = request_data.get("preliminary_findings") or []
    known_weaknesses = request_data.get("known_weaknesses") or []
    assets = request_data.get("assets") or []
    controls = request_data.get("applied_controls") or []
    remediation_actions = request_data.get("remediation_actions") or []
    framework_mappings = request_data.get("framework_mappings") or []

    primary_asset = assets[0] if assets else {}
    primary_control = controls[0] if controls else {}
    primary_action = remediation_actions[0] if remediation_actions else {}
    primary_mapping = framework_mappings[0] if framework_mappings else {}
    scope_label = (
        primary_asset.get("title") or request_data.get("scenario_name") or "the assessed scope"
    )

    sources: list[tuple[dict[str, Any], str]] = [(finding, "finding") for finding in findings]
    sources.extend(
        ({"title": weakness, "reference": None, "description": None}, "weakness")
        for weakness in known_weaknesses
    )
    if not sources and assets:
        sources = [(asset, "asset") for asset in assets]

    risk_scenarios: list[dict[str, Any]] = []
    warnings: list[dict[str, Any]] = []

    for source, source_kind in sources:
        if len(risk_scenarios) >= MAX_RISK_SCENARIOS:
            break
        source_title = (source.get("title") or "").strip()
        if not source_title:
            continue

        index = len(risk_scenarios) + 1
        likelihood = "high" if source_kind == "finding" else "medium"
        impact = "high" if _is_identity_related(source_title) else "medium"
        risk_scenarios.append(
            {
                "temporary_id": f"risk_scenario_{index}",
                "title": _fallback_title(source_kind, source_title, scope_label),
                "description": (
                    f"Weaknesses described by '{source_title}' could be exploited against "
                    f"{scope_label}, leading to unauthorized activity that the reviewed "
                    "controls do not yet demonstrably prevent."
                ),
                "asset_reference": primary_asset.get("reference") or "",
                "asset_title": primary_asset.get("title") or "",
                "linked_finding_reference": (
                    (source.get("reference") or "") if source_kind == "finding" else ""
                ),
                "linked_finding_title": source_title if source_kind == "finding" else "",
                "linked_applied_control_reference": primary_control.get("reference") or "",
                "linked_applied_control_title": primary_control.get("title") or "",
                "linked_remediation_action_reference": primary_action.get("reference") or "",
                "linked_remediation_action_title": primary_action.get("title") or "",
                "linked_framework_control_reference": primary_mapping.get("reference") or "",
                "linked_framework_control_code": primary_mapping.get("code") or "",
                "linked_framework_control_title": primary_mapping.get("title") or "",
                "threat": _fallback_threat(source_title),
                "vulnerability": source_title[:500],
                "impact_description": (
                    f"Unauthorized or unmonitored activity affecting {scope_label}, including "
                    "possible loss of confidentiality, integrity, or availability."
                ),
                "likelihood": likelihood,
                "impact": impact,
                "risk_level": _combine_severity(likelihood, impact),
                "rationale": (
                    f"Derived from the supplied "
                    f"{'preliminary finding' if source_kind == 'finding' else 'onboarding context item'} "
                    f"'{source_title}'. This is an advisory draft that requires human review; "
                    "no risk record is created and no risk treatment is chosen."
                ),
                "recommended_next_steps": [
                    "Confirm the scenario with the control owner and the asset owner.",
                    "Collect the evidence that would confirm or refute the exposure.",
                    "Rate likelihood and impact on the platform risk matrix during human review.",
                ],
                "confidence": 0.7 if source_kind == "finding" else 0.6,
                "review_status": REVIEW_STATUS,
            }
        )

    if not risk_scenarios:
        warnings.append(
            {
                "code": "no_risk_scenario_derived",
                "message": (
                    "The supplied context contained no readable finding, weakness, or asset "
                    "title, so no risk scenario could be drafted."
                ),
                "affected_fields": ["preliminary_findings", "known_weaknesses", "assets"],
                "needs_review": True,
            }
        )

    return {
        "provider_mode": "provider_not_configured_fallback",
        "overall_confidence": 0.0,
        "risk_scenarios": risk_scenarios,
        "warnings": warnings,
        "ambiguity_flags": [],
    }


def _fallback_title(source_kind: str, source_title: str, scope_label: str) -> str:
    prefix = "Exposure of" if source_kind != "asset" else "Risk to"
    return f"{prefix} {scope_label} due to {source_title}"[:MAX_TITLE_LENGTH]


def _fallback_threat(source_title: str) -> str:
    if _is_identity_related(source_title):
        return "Unauthorized access by an external or internal actor"
    return "Threat actor exploiting an unmitigated control weakness"


def _is_identity_related(value: str) -> bool:
    lowered = (value or "").lower()
    return any(token in lowered for token in IDENTITY_TOKENS)


def _combine_severity(likelihood: str, impact: str) -> str:
    """Readable advisory risk level. Never a platform risk-matrix rating."""
    try:
        rank = max(_SEVERITY_ORDER.index(likelihood), _SEVERITY_ORDER.index(impact))
    except ValueError:
        return "medium"
    return _SEVERITY_ORDER[rank]


# ---- Normalization -------------------------------------------------------------------


def _normalize_request_data(request_data: dict[str, Any]) -> dict[str, Any]:
    normalized = dict(request_data)
    normalized["user_locale"] = normalized.get("user_locale") or DEFAULT_USER_LOCALE
    normalized["strict_mode"] = bool(normalized.get("strict_mode", True))
    normalized["known_weaknesses"] = list(normalized.get("known_weaknesses") or [])
    for field in (
        "assets",
        "applied_controls",
        "evidence_requests",
        "audit_questions",
        "preliminary_findings",
        "remediation_actions",
        "framework_mappings",
    ):
        normalized[field] = list(normalized.get(field) or [])
    normalized["folder_reference"] = normalized.get("folder_reference") or {}
    normalized["assessment_reference"] = normalized.get("assessment_reference") or {}
    return normalized


def _annotate_provider_mode(
    draft: dict[str, Any],
    *,
    provider_mode: str,
    warning: dict[str, Any] | None = None,
) -> None:
    draft["provider_mode"] = provider_mode
    if warning is not None:
        warnings = draft.setdefault("warnings", [])
        if not any(
            isinstance(item, dict) and item.get("code") == warning["code"] for item in warnings
        ):
            warnings.append(warning)


def _enrich_draft(draft: dict[str, Any]) -> None:
    draft.setdefault("provider_mode", "configured_local_provider")
    draft.setdefault("warnings", [])
    draft["ambiguity_flags"] = _normalize_ambiguity_flags(draft.get("ambiguity_flags"))

    scenarios = draft.get("risk_scenarios")
    if isinstance(scenarios, list):
        normalized = [
            _normalize_scenario(index, scenario) if isinstance(scenario, dict) else scenario
            for index, scenario in enumerate(scenarios, start=1)
        ]
        if len(normalized) > MAX_RISK_SCENARIOS:
            _annotate_provider_mode(
                draft,
                provider_mode=draft["provider_mode"],
                warning={
                    "code": "risk_scenarios_trimmed",
                    "message": (
                        f"Step 8A kept the first {MAX_RISK_SCENARIOS} advisory risk scenarios "
                        f"for review; {len(normalized) - MAX_RISK_SCENARIOS} further "
                        "suggestions were trimmed."
                    ),
                    "affected_fields": ["risk_scenarios"],
                    "needs_review": True,
                },
            )
        draft["risk_scenarios"] = normalized[:MAX_RISK_SCENARIOS]

    _refresh_overall_confidence(draft)


def _normalize_scenario(index: int, scenario: dict[str, Any]) -> dict[str, Any]:
    """Fix harmless provider formatting only.

    Whitespace, letter case on the enum fields, numeric strings for confidence, and the
    positional temporary_id are normalized. Missing or invalid substance (title,
    description, rationale, unknown enum value, out-of-range confidence) is left untouched
    so the Step 8A guardrails reject it.
    """
    cleaned = {key: value for key, value in scenario.items() if key in ALLOWED_SCENARIO_KEYS}

    for key in TEXT_SCENARIO_KEYS:
        value = cleaned.get(key)
        if isinstance(value, str):
            cleaned[key] = value.strip()

    if not cleaned.get("temporary_id"):
        cleaned["temporary_id"] = f"risk_scenario_{index}"

    title = cleaned.get("title")
    if isinstance(title, str) and len(title) > MAX_TITLE_LENGTH:
        cleaned["title"] = title[:MAX_TITLE_LENGTH]

    for key, choices in ENUM_KEYS:
        value = cleaned.get(key)
        if isinstance(value, str):
            lowered = value.strip().lower()
            cleaned[key] = lowered if lowered in choices else value.strip()

    confidence = cleaned.get("confidence")
    if isinstance(confidence, str):
        try:
            cleaned["confidence"] = float(confidence.strip())
        except ValueError:
            pass

    next_steps = cleaned.get("recommended_next_steps")
    if isinstance(next_steps, list):
        cleaned["recommended_next_steps"] = [
            entry.strip() if isinstance(entry, str) else entry for entry in next_steps
        ]

    for key in OPTIONAL_LINK_KEYS:
        if not isinstance(cleaned.get(key), str):
            cleaned[key] = ""

    if not cleaned.get("review_status"):
        cleaned["review_status"] = REVIEW_STATUS

    return cleaned


def _normalize_ambiguity_flags(value: Any) -> list[dict[str, str]]:
    """Coerce provider-supplied ambiguity flags into the {code, message} contract.

    Local providers sometimes return ambiguity_flags as bare strings, matching the
    normalization already applied in Steps 5A, 6A, and 7A.
    """
    if not isinstance(value, list):
        return []

    normalized: list[dict[str, str]] = []
    for flag in value:
        if isinstance(flag, str):
            message = flag.strip()
            if message:
                normalized.append({"code": "provider_ambiguity", "message": message})
        elif isinstance(flag, dict):
            code = str(flag.get("code") or "provider_ambiguity").strip() or "provider_ambiguity"
            message = flag.get("message")
            if not isinstance(message, str) or not message.strip():
                message = str(flag.get("code") or "Ambiguity flagged by provider.")
            normalized.append({"code": code, "message": message.strip()})
        # Non-string, non-dict entries are dropped (treated as invalid).
    return normalized


def _refresh_overall_confidence(draft: dict[str, Any]) -> None:
    scores: list[float] = []
    for scenario in draft.get("risk_scenarios") or []:
        if not isinstance(scenario, dict):
            continue
        score = scenario.get("confidence")
        if isinstance(score, (int, float)) and not isinstance(score, bool):
            if 0.0 <= float(score) <= 1.0:
                scores.append(float(score))
    draft["overall_confidence"] = round(sum(scores) / len(scores), 2) if scores else 0.0
