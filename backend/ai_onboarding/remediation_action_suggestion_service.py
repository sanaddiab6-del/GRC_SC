from __future__ import annotations

from pathlib import Path
from typing import Any

from .remediation_action_suggestion_guardrails import (
    RemediationActionSuggestionDraftValidationError,
    validate_remediation_action_suggestion_guardrails,
)
from .remediation_action_suggestion_provider import (
    RemediationActionSuggestionProviderError,
    get_remediation_action_suggestion_provider,
)
from .remediation_action_suggestion_serializers import (
    AiRemediationActionSuggestionDraftSerializer,
    DEFAULT_USER_LOCALE,
    PRIORITY_CHOICES,
)


# Step 6A is advisory-only: the response carries no ids, no write flags, and no
# approval flags. Every action stays at review_status 'pending_review'.
REVIEW_STATUS = "pending_review"

ALLOWED_ACTION_KEYS = {
    "temporary_id",
    "title",
    "description",
    "linked_finding_reference",
    "linked_finding_title",
    "linked_asset_reference",
    "linked_asset_title",
    "linked_control_reference",
    "linked_control_title",
    "priority",
    "suggested_owner",
    "target_timeline",
    "success_criteria",
    "required_follow_up_evidence",
    "rationale",
    "confidence",
    "review_status",
}

OPTIONAL_LINK_KEYS = (
    "linked_finding_reference",
    "linked_finding_title",
    "linked_asset_reference",
    "linked_asset_title",
    "linked_control_reference",
    "linked_control_title",
)

TEXT_ACTION_KEYS = (
    "temporary_id",
    "title",
    "description",
    "suggested_owner",
    "target_timeline",
    "rationale",
    *OPTIONAL_LINK_KEYS,
)

MAX_TITLE_LENGTH = 200

IDENTITY_TOKENS = (
    "mfa",
    "multi-factor",
    "multifactor",
    "access",
    "identity",
    "privileged",
    "pam",
    "password",
    "authentication",
)


class AiRemediationActionSuggestionService:
    def __init__(self, *, base_dir: str | None = None, provider=None):
        self.base_dir = base_dir or str(Path(__file__).resolve().parents[1])
        self.provider = provider

    def build_remediation_action_suggestion_draft(
        self, request_data: dict[str, Any]
    ) -> dict[str, Any]:
        normalized = _normalize_request_data(request_data)

        provider = (
            self.provider
            if self.provider is not None
            else get_remediation_action_suggestion_provider()
        )

        if provider is None:
            draft = build_remediation_action_suggestion_fallback_draft(normalized)
            _annotate_provider_mode(
                draft,
                provider_mode="provider_not_configured_fallback",
                warning={
                    "code": "provider_not_configured_fallback",
                    "message": "No AI provider is configured; the advisory remediation action draft was generated by the deterministic fallback.",
                    "affected_fields": ["remediation_actions"],
                    "needs_review": True,
                },
            )
        else:
            try:
                draft = provider.build_remediation_action_suggestion_draft(normalized)
                _annotate_provider_mode(draft, provider_mode="configured_local_provider")
            except RemediationActionSuggestionProviderError as exc:
                if not exc.allow_fallback:
                    raise
                draft = build_remediation_action_suggestion_fallback_draft(normalized)
                _annotate_provider_mode(
                    draft,
                    provider_mode="local_provider_error_fallback",
                    warning={
                        "code": "local_provider_error_fallback",
                        "message": exc.detail,
                        "affected_fields": ["remediation_actions"],
                        "needs_review": True,
                    },
                )

        _enrich_draft(draft, normalized)

        validate_remediation_action_suggestion_guardrails(draft)

        serializer = AiRemediationActionSuggestionDraftSerializer(data=draft)
        if not serializer.is_valid():
            raise RemediationActionSuggestionDraftValidationError(
                "ai_remediation_action_suggestion_draft_validation_failed",
                "Generated advisory remediation action draft did not pass contract validation.",
                serializer.errors,
            )

        validated_draft = serializer.data
        validate_remediation_action_suggestion_guardrails(validated_draft)
        return validated_draft


def build_remediation_action_suggestion_draft(
    request_data: dict[str, Any],
    *,
    base_dir: str | None = None,
    provider=None,
) -> dict[str, Any]:
    service = AiRemediationActionSuggestionService(base_dir=base_dir, provider=provider)
    return service.build_remediation_action_suggestion_draft(request_data)


def build_remediation_action_suggestion_fallback_draft(
    request_data: dict[str, Any],
) -> dict[str, Any]:
    """Deterministic advisory draft used when no local provider is available.

    It never reads or writes the database: every value is derived from the readable
    request context only.
    """
    findings = request_data.get("preliminary_findings") or []
    known_weaknesses = request_data.get("known_weaknesses") or []
    assets = request_data.get("assets") or []
    controls = request_data.get("applied_controls") or []

    primary_asset = assets[0] if assets else {}
    primary_control = controls[0] if controls else {}
    scope_label = primary_asset.get("title") or request_data.get("scenario_name") or "the assessed scope"

    remediation_actions: list[dict[str, Any]] = []
    warnings: list[dict[str, Any]] = []

    sources: list[tuple[dict[str, Any], str]] = [(finding, "finding") for finding in findings]
    if not sources:
        sources = [
            ({"title": weakness, "reference": None, "description": None}, "weakness")
            for weakness in known_weaknesses
        ]

    for index, (source, source_kind) in enumerate(sources, start=1):
        source_title = (source.get("title") or "").strip()
        priority = "high" if source_kind == "finding" else "medium"
        remediation_actions.append(
            {
                "temporary_id": f"remediation_action_{index}",
                "title": f"Remediate: {source_title}"[:MAX_TITLE_LENGTH],
                "description": (
                    f"Plan and implement corrective action for '{source_title}' covering {scope_label}."
                ),
                "linked_finding_reference": (source.get("reference") or "") if source_kind == "finding" else "",
                "linked_finding_title": source_title if source_kind == "finding" else "",
                "linked_asset_reference": primary_asset.get("reference") or "",
                "linked_asset_title": primary_asset.get("title") or "",
                "linked_control_reference": primary_control.get("reference") or "",
                "linked_control_title": primary_control.get("title") or "",
                "priority": priority,
                "suggested_owner": _suggested_owner(source_title),
                "target_timeline": "30-60 days" if priority == "high" else "60-90 days",
                "success_criteria": [
                    f"The gap described by '{source_title}' is closed and verified.",
                    "Any exceptions are documented and approved by the accountable owner.",
                    "Operational records demonstrating the corrective action are retained.",
                ],
                "required_follow_up_evidence": [
                    "Updated policy or procedure document",
                    "Configuration or implementation evidence",
                    "Operational logs or records covering the review period",
                    "Exception approval records if applicable",
                ],
                "rationale": (
                    f"Derived from the supplied {'preliminary finding' if source_kind == 'finding' else 'known weakness'} "
                    f"'{source_title}'. This is an advisory draft that requires human review before any action is recorded."
                ),
                "confidence": 0.7 if source_kind == "finding" else 0.6,
                "review_status": REVIEW_STATUS,
            }
        )

    if not remediation_actions:
        warnings.append(
            {
                "code": "no_remediation_input_context",
                "message": "No preliminary findings or known weaknesses were supplied, so no remediation actions could be drafted.",
                "affected_fields": ["preliminary_findings", "known_weaknesses"],
                "needs_review": True,
            }
        )

    return {
        "provider_mode": "provider_not_configured_fallback",
        "overall_confidence": 0.0,
        "remediation_actions": remediation_actions,
        "warnings": warnings,
        "ambiguity_flags": [],
    }


def _suggested_owner(source_title: str) -> str:
    lowered = (source_title or "").lower()
    if any(token in lowered for token in IDENTITY_TOKENS):
        return "IAM / Security Operations"
    return "Security Operations"


def _normalize_request_data(request_data: dict[str, Any]) -> dict[str, Any]:
    normalized = dict(request_data)
    normalized["user_locale"] = normalized.get("user_locale") or DEFAULT_USER_LOCALE
    normalized["strict_mode"] = bool(normalized.get("strict_mode", True))
    normalized["known_weaknesses"] = list(normalized.get("known_weaknesses") or [])
    for field in (
        "assets",
        "applied_controls",
        "evidence_requests",
        "audit_questions",
        "preliminary_findings",
    ):
        normalized[field] = list(normalized.get(field) or [])
    normalized["folder_reference"] = normalized.get("folder_reference") or {}
    return normalized


def _annotate_provider_mode(
    draft: dict[str, Any],
    *,
    provider_mode: str,
    warning: dict[str, Any] | None = None,
) -> None:
    draft["provider_mode"] = provider_mode
    if warning is not None:
        warnings = draft.setdefault("warnings", [])
        if not any(
            isinstance(item, dict) and item.get("code") == warning["code"] for item in warnings
        ):
            warnings.append(warning)


def _enrich_draft(draft: dict[str, Any], request_data: dict[str, Any]) -> None:
    draft.setdefault("provider_mode", "configured_local_provider")
    draft.setdefault("warnings", [])
    draft["ambiguity_flags"] = _normalize_ambiguity_flags(draft.get("ambiguity_flags"))

    actions = draft.get("remediation_actions")
    if isinstance(actions, list):
        draft["remediation_actions"] = [
            _normalize_action(index, action) if isinstance(action, dict) else action
            for index, action in enumerate(actions, start=1)
        ]

    _refresh_overall_confidence(draft)


def _normalize_action(index: int, action: dict[str, Any]) -> dict[str, Any]:
    """Fix harmless provider formatting only.

    Whitespace, letter case on the priority enum, numeric strings for confidence, and
    the positional temporary_id are normalized. Missing or invalid substance (title,
    description, owner, timeline, criteria, evidence, rationale, out-of-range
    confidence, unknown priority) is left untouched so the Step 6A guardrails reject it.
    """
    cleaned = {key: value for key, value in action.items() if key in ALLOWED_ACTION_KEYS}

    for key in TEXT_ACTION_KEYS:
        value = cleaned.get(key)
        if isinstance(value, str):
            cleaned[key] = value.strip()

    if not cleaned.get("temporary_id"):
        cleaned["temporary_id"] = f"remediation_action_{index}"

    title = cleaned.get("title")
    if isinstance(title, str) and len(title) > MAX_TITLE_LENGTH:
        cleaned["title"] = title[:MAX_TITLE_LENGTH]

    priority = cleaned.get("priority")
    if isinstance(priority, str):
        lowered = priority.strip().lower()
        cleaned["priority"] = lowered if lowered in PRIORITY_CHOICES else priority.strip()

    confidence = cleaned.get("confidence")
    if isinstance(confidence, str):
        try:
            cleaned["confidence"] = float(confidence.strip())
        except ValueError:
            pass

    for key in ("success_criteria", "required_follow_up_evidence"):
        value = cleaned.get(key)
        if isinstance(value, list):
            cleaned[key] = [entry.strip() if isinstance(entry, str) else entry for entry in value]

    for key in OPTIONAL_LINK_KEYS:
        if not isinstance(cleaned.get(key), str):
            cleaned[key] = ""

    if not cleaned.get("review_status"):
        cleaned["review_status"] = REVIEW_STATUS

    return cleaned


def _normalize_ambiguity_flags(value: Any) -> list[dict[str, str]]:
    """Coerce provider-supplied ambiguity flags into the {code, message} contract.

    Local providers sometimes return ambiguity_flags as bare strings, matching the
    normalization already applied in Step 5A.
    """
    if not isinstance(value, list):
        return []

    normalized: list[dict[str, str]] = []
    for flag in value:
        if isinstance(flag, str):
            message = flag.strip()
            if message:
                normalized.append({"code": "provider_ambiguity", "message": message})
        elif isinstance(flag, dict):
            code = str(flag.get("code") or "provider_ambiguity").strip() or "provider_ambiguity"
            message = flag.get("message")
            if not isinstance(message, str) or not message.strip():
                message = str(flag.get("code") or "Ambiguity flagged by provider.")
            normalized.append({"code": code, "message": message.strip()})
        # Non-string, non-dict entries are dropped (treated as invalid).
    return normalized


def _refresh_overall_confidence(draft: dict[str, Any]) -> None:
    scores: list[float] = []
    for action in draft.get("remediation_actions") or []:
        if not isinstance(action, dict):
            continue
        score = action.get("confidence")
        if isinstance(score, (int, float)) and not isinstance(score, bool):
            if 0.0 <= float(score) <= 1.0:
                scores.append(float(score))
    draft["overall_confidence"] = round(sum(scores) / len(scores), 2) if scores else 0.0
