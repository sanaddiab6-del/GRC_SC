from __future__ import annotations

from pathlib import Path
from typing import Any

from .audit_report_suggestion_guardrails import (
    AuditReportSuggestionDraftValidationError,
    validate_audit_report_suggestion_guardrails,
)
from .audit_report_suggestion_provider import (
    AuditReportSuggestionProviderError,
    get_audit_report_suggestion_provider,
)
from .audit_report_suggestion_serializers import (
    AiAuditReportSuggestionDraftSerializer,
    DEFAULT_USER_LOCALE,
    EXPECTED_SECTION_HEADINGS,
    MAX_LIST_ITEMS,
    MAX_REPORT_SECTIONS,
    MAX_SECTION_CONTENT_LENGTH,
)


# Step 11A is advisory-only: the response carries no ids, no write flags, and no approval
# flags. The draft always stays at review_status 'pending_review'.
REVIEW_STATUS = "pending_review"

DEFAULT_REPORT_TITLE = "AI-assisted GRC onboarding report draft"

ALLOWED_DRAFT_KEYS = {
    "provider_mode",
    "report_title",
    "overall_confidence",
    "report_sections",
    "executive_summary",
    "limitations",
    "recommended_next_steps",
    "warnings",
    "ambiguity_flags",
    "review_status",
}

ALLOWED_SECTION_KEYS = {"heading", "content", "source_items", "confidence"}

CONTEXT_FIELDS = (
    "assets",
    "applied_controls",
    "evidence_requests",
    "audit_questions",
    "preliminary_findings",
    "remediation_actions",
    "framework_mappings",
    "risk_scenarios",
    "control_effectiveness_suggestions",
)

# The mandatory limitation the deterministic fallback always states. The guardrails require
# an equivalent statement from any provider-generated draft too.
HUMAN_REVIEW_LIMITATION = (
    "This is an AI-assisted draft. Human review by the accountable auditor is required "
    "before any part of it is used or shared."
)

STANDARD_LIMITATIONS = (
    HUMAN_REVIEW_LIMITATION,
    "The draft reflects only the onboarding context captured in Steps 1-10; it is not based "
    "on independently verified evidence.",
    "No statement in this draft is a final audit opinion, a compliance conclusion, or a "
    "regulator-recognised result.",
    "Findings, risk scenarios, and control judgements remain advisory until confirmed by "
    "their owners.",
)

EMPTY_SECTION_TEXT = "No reviewed onboarding context was supplied for this section."


class AiAuditReportSuggestionService:
    def __init__(self, *, base_dir: str | None = None, provider=None):
        self.base_dir = base_dir or str(Path(__file__).resolve().parents[1])
        self.provider = provider

    def build_audit_report_suggestion_draft(
        self, request_data: dict[str, Any]
    ) -> dict[str, Any]:
        normalized = _normalize_request_data(request_data)

        if not _has_report_context(normalized):
            # Nothing reviewed to report on: Step 11A refuses rather than inventing a report.
            return _finalize(_build_blocked_draft())

        provider = (
            self.provider
            if self.provider is not None
            else get_audit_report_suggestion_provider()
        )

        if provider is None:
            draft = build_audit_report_suggestion_fallback_draft(normalized)
            _annotate_provider_mode(
                draft,
                provider_mode="provider_not_configured_fallback",
                warning={
                    "code": "provider_not_configured_fallback",
                    "message": (
                        "No AI provider is configured; the report draft was generated by the "
                        "deterministic fallback."
                    ),
                    "affected_fields": ["report_sections", "executive_summary"],
                    "needs_review": True,
                },
            )
        else:
            try:
                draft = provider.build_audit_report_suggestion_draft(normalized)
                _annotate_provider_mode(draft, provider_mode="configured_local_provider")
            except AuditReportSuggestionProviderError as exc:
                if not exc.allow_fallback:
                    raise
                draft = build_audit_report_suggestion_fallback_draft(normalized)
                _annotate_provider_mode(
                    draft,
                    provider_mode="local_provider_error_fallback",
                    warning={
                        "code": "local_provider_error_fallback",
                        "message": exc.detail,
                        "affected_fields": ["report_sections", "executive_summary"],
                        "needs_review": True,
                    },
                )

        _enrich_draft(draft, normalized)
        return _finalize(draft)


def build_audit_report_suggestion_draft(
    request_data: dict[str, Any],
    *,
    base_dir: str | None = None,
    provider=None,
) -> dict[str, Any]:
    service = AiAuditReportSuggestionService(base_dir=base_dir, provider=provider)
    return service.build_audit_report_suggestion_draft(request_data)


def _finalize(draft: dict[str, Any]) -> dict[str, Any]:
    validate_audit_report_suggestion_guardrails(draft)

    serializer = AiAuditReportSuggestionDraftSerializer(data=draft)
    if not serializer.is_valid():
        raise AuditReportSuggestionDraftValidationError(
            "ai_audit_report_suggestion_draft_validation_failed",
            "Generated advisory audit report draft did not pass contract validation.",
            serializer.errors,
        )

    validated_draft = serializer.data
    validate_audit_report_suggestion_guardrails(validated_draft)
    return validated_draft


def _has_report_context(request_data: dict[str, Any]) -> bool:
    return bool(
        any(request_data.get(field) for field in CONTEXT_FIELDS)
        or request_data.get("known_weaknesses")
        or request_data.get("evidence_gaps")
    )


def _build_blocked_draft() -> dict[str, Any]:
    return {
        "provider_mode": "report_context_missing_blocked",
        "report_title": DEFAULT_REPORT_TITLE,
        "overall_confidence": 0.0,
        "report_sections": [],
        "executive_summary": (
            "No reviewed onboarding context was supplied, so no report draft could be "
            "produced. Nothing is asserted about the assessment."
        ),
        "limitations": list(STANDARD_LIMITATIONS),
        "recommended_next_steps": [
            "Complete the earlier onboarding steps, then run Step 11A again."
        ],
        "warnings": [
            {
                "code": "no_report_input_context",
                "message": (
                    "No assets, controls, evidence, findings, remediation actions, mappings, "
                    "risks, effectiveness judgements, gaps, or known weaknesses were supplied, "
                    "so Step 11A produced no report sections."
                ),
                "affected_fields": list(CONTEXT_FIELDS),
                "needs_review": True,
            }
        ],
        "ambiguity_flags": [
            {
                "code": "no_report_input_context",
                "message": "Complete Steps 3A-10B before Step 11A can draft the report.",
            }
        ],
        "review_status": REVIEW_STATUS,
    }


# ---- Deterministic fallback ----------------------------------------------------------


def build_audit_report_suggestion_fallback_draft(
    request_data: dict[str, Any],
) -> dict[str, Any]:
    """Deterministic report draft used when no local provider is available.

    It never reads or writes the database: every section is composed from the readable
    request context only, and it never asserts an audit conclusion.
    """
    organization = request_data.get("organization_name") or "the organization"
    scenario = request_data.get("scenario_name") or "the assessed scope"
    framework = request_data.get("framework_name")
    readiness = request_data.get("audit_readiness") or {}

    sections: list[dict[str, Any]] = []

    executive_summary = (
        f"This draft summarizes the AI-assisted GRC onboarding performed for {organization} "
        f"covering {scenario}"
        + (f" against {framework}" if framework else "")
        + ". It records what the onboarding flow captured and what still requires human "
        "review. It is not an audit opinion and asserts no compliance conclusion."
    )
    sections.append(
        _section("Executive Summary", executive_summary, [], 0.6)
    )
    sections.append(
        _section(
            "Scope",
            f"The reviewed scope is {scenario}"
            + (f", assessed against {framework}" if framework else "")
            + ". "
            + (request_data.get("case_summary") or ""),
            [],
            0.6,
        )
    )
    sections.append(_titles_section("Assets in Scope", request_data.get("assets")))
    sections.append(
        _strings_section("Known Weaknesses", request_data.get("known_weaknesses"))
    )
    sections.append(
        _titles_section("Applied Controls", request_data.get("applied_controls"))
    )
    sections.append(
        _titles_section("Evidence Requested", request_data.get("evidence_requests"))
    )
    sections.append(
        _titles_section("Audit Questions", request_data.get("audit_questions"))
    )
    sections.append(
        _titles_section("Preliminary Findings", request_data.get("preliminary_findings"))
    )
    sections.append(
        _titles_section("Remediation Actions", request_data.get("remediation_actions"))
    )
    sections.append(
        _titles_section("Framework Control Mappings", request_data.get("framework_mappings"))
    )
    sections.append(_titles_section("Risk Scenarios", request_data.get("risk_scenarios")))
    sections.append(
        _titles_section(
            "Control Effectiveness / Compliance Suggestions",
            request_data.get("control_effectiveness_suggestions"),
        )
    )
    sections.append(_strings_section("Evidence Gaps", request_data.get("evidence_gaps")))

    readiness_status = readiness.get("readiness_status")
    readiness_content = (
        f"Advisory readiness status: {readiness_status} "
        f"(advisory score {readiness.get('readiness_score')}/100). "
        f"{readiness.get('summary') or ''}".strip()
        if readiness_status
        else "No audit readiness summary was supplied."
    )
    sections.append(_section("Audit Readiness", readiness_content, [], 0.6))

    recommended_next_steps = [
        "Review every advisory item in this draft with its accountable owner.",
        "Collect the outstanding evidence and answer the open audit questions.",
        "Confirm or dismiss each preliminary finding and record the reviewed result.",
        "Rate the suggested risk scenarios on the platform risk matrix.",
    ]
    sections.append(
        _section(
            "Recommended Next Steps",
            " ".join(recommended_next_steps),
            [],
            0.6,
        )
    )
    sections.append(
        _section(
            "Limitations / Human Review Required",
            " ".join(STANDARD_LIMITATIONS),
            [],
            0.6,
        )
    )

    return {
        "provider_mode": "provider_not_configured_fallback",
        "report_title": (
            f"AI-assisted GRC onboarding report draft - {organization} - {scenario}"
        )[:300],
        "overall_confidence": 0.0,
        "report_sections": sections,
        "executive_summary": executive_summary,
        "limitations": list(STANDARD_LIMITATIONS),
        "recommended_next_steps": recommended_next_steps,
        "warnings": [],
        "ambiguity_flags": [],
        "review_status": REVIEW_STATUS,
    }


def _section(
    heading: str, content: str, source_items: list[str], confidence: float
) -> dict[str, Any]:
    return {
        "heading": heading,
        "content": (content or EMPTY_SECTION_TEXT).strip()[:MAX_SECTION_CONTENT_LENGTH],
        "source_items": source_items[:MAX_LIST_ITEMS],
        "confidence": confidence,
    }


def _titles_section(heading: str, items: Any) -> dict[str, Any]:
    titles = _titles(items or [])
    if not titles:
        return _section(heading, EMPTY_SECTION_TEXT, [], 0.5)
    return _section(
        heading,
        f"{len(titles)} item(s) captured during onboarding: " + "; ".join(titles) + ".",
        titles,
        0.65,
    )


def _strings_section(heading: str, entries: Any) -> dict[str, Any]:
    values = [
        entry.strip() for entry in (entries or []) if isinstance(entry, str) and entry.strip()
    ]
    if not values:
        return _section(heading, EMPTY_SECTION_TEXT, [], 0.5)
    return _section(
        heading,
        f"{len(values)} item(s) recorded: " + "; ".join(values) + ".",
        values[:MAX_LIST_ITEMS],
        0.65,
    )


def _titles(items: list[Any]) -> list[str]:
    titles: list[str] = []
    for item in items:
        if not isinstance(item, dict):
            continue
        title = (item.get("title") or "").strip()
        if title and title not in titles:
            titles.append(title[:500])
    return titles


# ---- Normalization -------------------------------------------------------------------


def _normalize_request_data(request_data: dict[str, Any]) -> dict[str, Any]:
    normalized = dict(request_data)
    normalized["user_locale"] = normalized.get("user_locale") or DEFAULT_USER_LOCALE
    normalized["strict_mode"] = bool(normalized.get("strict_mode", True))
    normalized["known_weaknesses"] = list(normalized.get("known_weaknesses") or [])
    normalized["evidence_gaps"] = list(normalized.get("evidence_gaps") or [])
    for field in CONTEXT_FIELDS:
        normalized[field] = list(normalized.get(field) or [])
    normalized["folder_reference"] = normalized.get("folder_reference") or {}
    normalized["assessment_reference"] = normalized.get("assessment_reference") or {}
    normalized["audit_readiness"] = normalized.get("audit_readiness") or {}
    return normalized


def _annotate_provider_mode(
    draft: dict[str, Any],
    *,
    provider_mode: str,
    warning: dict[str, Any] | None = None,
) -> None:
    draft["provider_mode"] = provider_mode
    if warning is not None:
        warnings = draft.setdefault("warnings", [])
        if not any(
            isinstance(item, dict) and item.get("code") == warning["code"] for item in warnings
        ):
            warnings.append(warning)


def _enrich_draft(draft: dict[str, Any], request_data: dict[str, Any]) -> None:
    """Fix harmless provider formatting only.

    Whitespace, unknown keys, numeric strings for confidence, and list entry trimming are
    normalized. Missing or invalid substance (blank title, empty limitations, a missing
    human-review statement, out-of-range confidence) is left untouched so the Step 11A
    guardrails reject it.
    """
    for key in list(draft.keys()):
        if key not in ALLOWED_DRAFT_KEYS:
            del draft[key]

    draft.setdefault("provider_mode", "configured_local_provider")
    draft.setdefault("warnings", [])
    draft["ambiguity_flags"] = _normalize_ambiguity_flags(draft.get("ambiguity_flags"))

    for key in ("report_title", "executive_summary"):
        value = draft.get(key)
        if isinstance(value, str):
            draft[key] = value.strip()

    for key in ("limitations", "recommended_next_steps"):
        value = draft.get(key)
        if isinstance(value, list):
            draft[key] = [
                entry.strip() if isinstance(entry, str) else entry for entry in value
            ][:MAX_LIST_ITEMS]

    sections = draft.get("report_sections")
    if isinstance(sections, list):
        normalized = [
            _normalize_section(section) if isinstance(section, dict) else section
            for section in sections
        ]
        if len(normalized) > MAX_REPORT_SECTIONS:
            _annotate_provider_mode(
                draft,
                provider_mode=draft["provider_mode"],
                warning={
                    "code": "report_sections_trimmed",
                    "message": (
                        f"Step 11A kept the first {MAX_REPORT_SECTIONS} report sections for "
                        f"review; {len(normalized) - MAX_REPORT_SECTIONS} further sections "
                        "were trimmed."
                    ),
                    "affected_fields": ["report_sections"],
                    "needs_review": True,
                },
            )
        draft["report_sections"] = normalized[:MAX_REPORT_SECTIONS]
        _warn_missing_sections(draft)

    if not draft.get("review_status"):
        draft["review_status"] = REVIEW_STATUS

    _refresh_overall_confidence(draft)


def _normalize_section(section: dict[str, Any]) -> dict[str, Any]:
    cleaned = {key: value for key, value in section.items() if key in ALLOWED_SECTION_KEYS}

    for key in ("heading", "content"):
        value = cleaned.get(key)
        if isinstance(value, str):
            cleaned[key] = value.strip()

    content = cleaned.get("content")
    if isinstance(content, str) and len(content) > MAX_SECTION_CONTENT_LENGTH:
        cleaned["content"] = content[:MAX_SECTION_CONTENT_LENGTH]

    source_items = cleaned.get("source_items")
    if isinstance(source_items, list):
        cleaned["source_items"] = [
            entry.strip() if isinstance(entry, str) else entry for entry in source_items
        ][:MAX_LIST_ITEMS]
    elif source_items is None:
        cleaned["source_items"] = []

    confidence = cleaned.get("confidence")
    if isinstance(confidence, str):
        try:
            cleaned["confidence"] = float(confidence.strip())
        except ValueError:
            pass

    return cleaned


def _warn_missing_sections(draft: dict[str, Any]) -> None:
    present = {
        (section.get("heading") or "").strip().lower()
        for section in draft.get("report_sections") or []
        if isinstance(section, dict)
    }
    missing = [
        heading for heading in EXPECTED_SECTION_HEADINGS if heading.lower() not in present
    ]
    if not missing:
        return
    _annotate_provider_mode(
        draft,
        provider_mode=draft["provider_mode"],
        warning={
            "code": "report_sections_incomplete",
            "message": (
                "The report draft does not cover every expected section: "
                + ", ".join(missing)
                + ". Missing sections were not invented."
            ),
            "affected_fields": ["report_sections"],
            "needs_review": True,
        },
    )


def _normalize_ambiguity_flags(value: Any) -> list[dict[str, str]]:
    """Coerce provider-supplied ambiguity flags into the {code, message} contract."""
    if not isinstance(value, list):
        return []

    normalized: list[dict[str, str]] = []
    for flag in value:
        if isinstance(flag, str):
            message = flag.strip()
            if message:
                normalized.append({"code": "provider_ambiguity", "message": message})
        elif isinstance(flag, dict):
            code = str(flag.get("code") or "provider_ambiguity").strip() or "provider_ambiguity"
            message = flag.get("message")
            if not isinstance(message, str) or not message.strip():
                message = str(flag.get("code") or "Ambiguity flagged by provider.")
            normalized.append({"code": code, "message": message.strip()})
        # Non-string, non-dict entries are dropped (treated as invalid).
    return normalized


def _refresh_overall_confidence(draft: dict[str, Any]) -> None:
    scores: list[float] = []
    for section in draft.get("report_sections") or []:
        if not isinstance(section, dict):
            continue
        score = section.get("confidence")
        if isinstance(score, (int, float)) and not isinstance(score, bool):
            if 0.0 <= float(score) <= 1.0:
                scores.append(float(score))
    draft["overall_confidence"] = round(sum(scores) / len(scores), 2) if scores else 0.0
