from __future__ import annotations

from pathlib import Path
from typing import Any

from .audit_readiness_suggestion_guardrails import (
    AuditReadinessSuggestionDraftValidationError,
    REQUIRED_LIST_FIELDS,
    validate_audit_readiness_suggestion_guardrails,
)
from .audit_readiness_suggestion_provider import (
    AuditReadinessSuggestionProviderError,
    get_audit_readiness_suggestion_provider,
)
from .audit_readiness_suggestion_serializers import (
    AiAuditReadinessSuggestionDraftSerializer,
    DEFAULT_USER_LOCALE,
    MAX_READINESS_SCORE,
    MAX_SUMMARY_LIST_ITEMS,
    MIN_READINESS_SCORE,
    READINESS_STATUS_CHOICES,
)


# Step 10A is advisory-only: the response carries no ids, no write flags, and no approval
# flags. The summary always stays at review_status 'pending_review'.
REVIEW_STATUS = "pending_review"

MAX_LIST_ENTRY_LENGTH = 500

CONTEXT_FIELDS = (
    "assets",
    "applied_controls",
    "evidence_requests",
    "audit_questions",
    "preliminary_findings",
    "remediation_actions",
    "framework_mappings",
    "risk_scenarios",
    "control_effectiveness_suggestions",
)

ALLOWED_DRAFT_KEYS = {
    "provider_mode",
    "overall_confidence",
    "readiness_status",
    "readiness_score",
    "summary",
    *REQUIRED_LIST_FIELDS,
    "warnings",
    "ambiguity_flags",
    "review_status",
}

# Statuses that mark a control effectiveness suggestion as not yet demonstrable, used by
# the deterministic fallback to list blocked controls.
_BLOCKING_EFFECTIVENESS_STATUSES = {
    "ineffective",
    "not_assessed",
    "needs_more_evidence",
    "non_compliant",
    "partially_compliant",
}


class AiAuditReadinessSuggestionService:
    def __init__(self, *, base_dir: str | None = None, provider=None):
        self.base_dir = base_dir or str(Path(__file__).resolve().parents[1])
        self.provider = provider

    def build_audit_readiness_suggestion_draft(
        self, request_data: dict[str, Any]
    ) -> dict[str, Any]:
        normalized = _normalize_request_data(request_data)

        if not _has_readiness_context(normalized):
            # Nothing reviewed to summarize: Step 10A refuses rather than inventing a
            # readiness verdict.
            return _finalize(_build_blocked_draft())

        provider = (
            self.provider
            if self.provider is not None
            else get_audit_readiness_suggestion_provider()
        )

        if provider is None:
            draft = build_audit_readiness_suggestion_fallback_draft(normalized)
            _annotate_provider_mode(
                draft,
                provider_mode="provider_not_configured_fallback",
                warning={
                    "code": "provider_not_configured_fallback",
                    "message": (
                        "No AI provider is configured; the advisory audit readiness summary "
                        "was generated by the deterministic fallback."
                    ),
                    "affected_fields": ["summary", "readiness_status"],
                    "needs_review": True,
                },
            )
        else:
            try:
                draft = provider.build_audit_readiness_suggestion_draft(normalized)
                _annotate_provider_mode(draft, provider_mode="configured_local_provider")
            except AuditReadinessSuggestionProviderError as exc:
                if not exc.allow_fallback:
                    raise
                draft = build_audit_readiness_suggestion_fallback_draft(normalized)
                _annotate_provider_mode(
                    draft,
                    provider_mode="local_provider_error_fallback",
                    warning={
                        "code": "local_provider_error_fallback",
                        "message": exc.detail,
                        "affected_fields": ["summary", "readiness_status"],
                        "needs_review": True,
                    },
                )

        _enrich_draft(draft)
        return _finalize(draft)


def build_audit_readiness_suggestion_draft(
    request_data: dict[str, Any],
    *,
    base_dir: str | None = None,
    provider=None,
) -> dict[str, Any]:
    service = AiAuditReadinessSuggestionService(base_dir=base_dir, provider=provider)
    return service.build_audit_readiness_suggestion_draft(request_data)


def _finalize(draft: dict[str, Any]) -> dict[str, Any]:
    validate_audit_readiness_suggestion_guardrails(draft)

    serializer = AiAuditReadinessSuggestionDraftSerializer(data=draft)
    if not serializer.is_valid():
        raise AuditReadinessSuggestionDraftValidationError(
            "ai_audit_readiness_suggestion_draft_validation_failed",
            "Generated advisory audit readiness draft did not pass contract validation.",
            serializer.errors,
        )

    validated_draft = serializer.data
    validate_audit_readiness_suggestion_guardrails(validated_draft)
    return validated_draft


def _has_readiness_context(request_data: dict[str, Any]) -> bool:
    return bool(
        any(request_data.get(field) for field in CONTEXT_FIELDS)
        or request_data.get("known_weaknesses")
    )


def _build_blocked_draft() -> dict[str, Any]:
    return {
        "provider_mode": "readiness_context_missing_blocked",
        "overall_confidence": 0.0,
        "readiness_status": "blocked",
        "readiness_score": 0,
        "summary": (
            "No reviewed onboarding context was supplied, so audit readiness cannot be "
            "summarized. Nothing is asserted about the assessment."
        ),
        "ready_items": [],
        "missing_evidence": [],
        "open_findings": [],
        "open_risks": [],
        "blocked_controls": [],
        "recommended_next_steps": [
            "Complete the earlier onboarding steps, then run Step 10A again."
        ],
        "priority_actions": [],
        "warnings": [
            {
                "code": "no_readiness_input_context",
                "message": (
                    "No assets, controls, evidence, findings, remediation actions, mappings, "
                    "risks, or known weaknesses were supplied, so Step 10A produced no "
                    "readiness assessment."
                ),
                "affected_fields": list(CONTEXT_FIELDS),
                "needs_review": True,
            }
        ],
        "ambiguity_flags": [
            {
                "code": "no_readiness_input_context",
                "message": (
                    "Complete Steps 3A-9B before Step 10A can summarize audit readiness."
                ),
            }
        ],
        "review_status": REVIEW_STATUS,
    }


# ---- Deterministic fallback ----------------------------------------------------------


def build_audit_readiness_suggestion_fallback_draft(
    request_data: dict[str, Any],
) -> dict[str, Any]:
    """Deterministic advisory summary used when no local provider is available.

    It never reads or writes the database: every statement is derived from the readable
    request context only, and it never asserts an audit conclusion.
    """
    assets = request_data.get("assets") or []
    controls = request_data.get("applied_controls") or []
    mappings = request_data.get("framework_mappings") or []
    evidence_requests = request_data.get("evidence_requests") or []
    audit_questions = request_data.get("audit_questions") or []
    findings = request_data.get("preliminary_findings") or []
    remediation_actions = request_data.get("remediation_actions") or []
    risk_scenarios = request_data.get("risk_scenarios") or []
    effectiveness = request_data.get("control_effectiveness_suggestions") or []
    known_weaknesses = request_data.get("known_weaknesses") or []

    ready_items = [
        *(f"Asset in scope: {title}" for title in _titles(assets)),
        *(f"Applied control recorded: {title}" for title in _titles(controls)),
        *(f"Framework control mapped: {title}" for title in _titles(mappings)),
        *(f"Remediation action planned: {title}" for title in _titles(remediation_actions)),
    ]

    missing_evidence = [
        *(f"Evidence still to collect: {title}" for title in _titles(evidence_requests)),
        *(f"Audit question still open: {title}" for title in _titles(audit_questions)),
    ]

    open_findings = _titles(findings)
    open_risks = _titles(risk_scenarios)
    blocked_controls = [
        item.get("title", "").strip()
        for item in effectiveness
        if isinstance(item, dict)
        and (item.get("title") or "").strip()
        and _is_blocking_effectiveness(item)
    ]

    readiness_score = _fallback_score(
        ready_count=len(ready_items),
        missing_count=len(missing_evidence),
        finding_count=len(open_findings),
        risk_count=len(open_risks),
        blocked_count=len(blocked_controls),
    )
    readiness_status = _fallback_status(
        readiness_score,
        has_missing_evidence=bool(missing_evidence),
        has_open_findings=bool(open_findings),
    )

    recommended_next_steps = [
        "Collect and attach the outstanding evidence for each requested item.",
        "Answer the open audit questions with the control owners.",
        "Confirm or dismiss each preliminary finding with its owner.",
        "Review the suggested risk scenarios and rate them on the platform risk matrix.",
        "Record the reviewed control results on the requirement assessments.",
    ]
    priority_actions = [
        *(f"Resolve finding: {title}" for title in open_findings[:3]),
        *(f"Obtain evidence: {title}" for title in _titles(evidence_requests)[:3]),
    ] or ["Review the onboarding output with the accountable owner."]

    summary = (
        f"{len(ready_items)} reviewed onboarding item(s) are in place, "
        f"{len(missing_evidence)} evidence or question item(s) are still outstanding, "
        f"{len(open_findings)} preliminary finding(s) are open, and "
        f"{len(open_risks)} suggested risk scenario(s) await human rating. "
        "This is an advisory readiness summary for human review only; nothing has been "
        "marked ready and no audit conclusion is asserted."
    )

    warnings: list[dict[str, Any]] = []
    if known_weaknesses:
        warnings.append(
            {
                "code": "known_weaknesses_outstanding",
                "message": (
                    "Known weaknesses supplied at intake are still carried in the case: "
                    + "; ".join(known_weaknesses[:MAX_SUMMARY_LIST_ITEMS])
                ),
                "affected_fields": ["known_weaknesses"],
                "needs_review": True,
            }
        )

    return {
        "provider_mode": "provider_not_configured_fallback",
        "overall_confidence": 0.0,
        "readiness_status": readiness_status,
        "readiness_score": readiness_score,
        "summary": summary,
        "ready_items": ready_items,
        "missing_evidence": missing_evidence,
        "open_findings": open_findings,
        "open_risks": open_risks,
        "blocked_controls": blocked_controls,
        "recommended_next_steps": recommended_next_steps,
        "priority_actions": priority_actions,
        "warnings": warnings,
        "ambiguity_flags": [],
        "review_status": REVIEW_STATUS,
    }


def _titles(items: list[Any]) -> list[str]:
    titles: list[str] = []
    for item in items:
        if not isinstance(item, dict):
            continue
        title = (item.get("title") or "").strip()
        if title and title not in titles:
            titles.append(title[:MAX_LIST_ENTRY_LENGTH])
    return titles


def _is_blocking_effectiveness(item: dict[str, Any]) -> bool:
    status = (item.get("status") or "").strip().lower()
    if status:
        return status in _BLOCKING_EFFECTIVENESS_STATUSES
    # With no status carried over, a supplied effectiveness row is still awaiting review.
    return True


def _fallback_score(
    *,
    ready_count: int,
    missing_count: int,
    finding_count: int,
    risk_count: int,
    blocked_count: int,
) -> int:
    """Readable advisory score. Never a platform rating and never persisted."""
    total = ready_count + missing_count + finding_count + risk_count + blocked_count
    if total == 0:
        return 0
    score = round(100 * ready_count / total)
    return max(MIN_READINESS_SCORE, min(MAX_READINESS_SCORE, int(score)))


def _fallback_status(
    score: int, *, has_missing_evidence: bool, has_open_findings: bool
) -> str:
    if has_missing_evidence:
        return "needs_more_evidence"
    if has_open_findings:
        return "partially_ready"
    if score >= 80:
        return "partially_ready"
    return "not_ready"


# ---- Normalization -------------------------------------------------------------------


def _normalize_request_data(request_data: dict[str, Any]) -> dict[str, Any]:
    normalized = dict(request_data)
    normalized["user_locale"] = normalized.get("user_locale") or DEFAULT_USER_LOCALE
    normalized["strict_mode"] = bool(normalized.get("strict_mode", True))
    normalized["known_weaknesses"] = list(normalized.get("known_weaknesses") or [])
    for field in CONTEXT_FIELDS:
        normalized[field] = list(normalized.get(field) or [])
    normalized["folder_reference"] = normalized.get("folder_reference") or {}
    normalized["assessment_reference"] = normalized.get("assessment_reference") or {}
    return normalized


def _annotate_provider_mode(
    draft: dict[str, Any],
    *,
    provider_mode: str,
    warning: dict[str, Any] | None = None,
) -> None:
    draft["provider_mode"] = provider_mode
    if warning is not None:
        warnings = draft.setdefault("warnings", [])
        if not any(
            isinstance(item, dict) and item.get("code") == warning["code"] for item in warnings
        ):
            warnings.append(warning)


def _enrich_draft(draft: dict[str, Any]) -> None:
    """Fix harmless provider formatting only.

    Whitespace, letter case on readiness_status, numeric strings for readiness_score, and
    list entry trimming are normalized, and unknown keys are dropped. Missing or invalid
    substance (unknown status, out-of-range score, non-string list entries) is left
    untouched so the Step 10A guardrails reject it.
    """
    for key in list(draft.keys()):
        if key not in ALLOWED_DRAFT_KEYS:
            del draft[key]

    draft.setdefault("provider_mode", "configured_local_provider")
    draft.setdefault("warnings", [])
    draft["ambiguity_flags"] = _normalize_ambiguity_flags(draft.get("ambiguity_flags"))

    status = draft.get("readiness_status")
    if isinstance(status, str):
        lowered = status.strip().lower().replace(" ", "_")
        draft["readiness_status"] = (
            lowered if lowered in READINESS_STATUS_CHOICES else status.strip()
        )

    score = draft.get("readiness_score")
    if isinstance(score, str):
        try:
            draft["readiness_score"] = int(float(score.strip()))
        except ValueError:
            pass
    elif isinstance(score, float) and float(score).is_integer():
        draft["readiness_score"] = int(score)

    summary = draft.get("summary")
    if isinstance(summary, str):
        draft["summary"] = summary.strip()

    for field in REQUIRED_LIST_FIELDS:
        value = draft.get(field)
        if value is None:
            draft[field] = []
            continue
        if not isinstance(value, list):
            continue
        trimmed = [
            entry.strip()[:MAX_LIST_ENTRY_LENGTH] if isinstance(entry, str) else entry
            for entry in value
        ]
        if len(trimmed) > MAX_SUMMARY_LIST_ITEMS:
            _annotate_provider_mode(
                draft,
                provider_mode=draft["provider_mode"],
                warning={
                    "code": "readiness_list_trimmed",
                    "message": (
                        f"Step 10A kept the first {MAX_SUMMARY_LIST_ITEMS} entries of "
                        f"{field} for review; further entries were trimmed."
                    ),
                    "affected_fields": [field],
                    "needs_review": True,
                },
            )
        draft[field] = trimmed[:MAX_SUMMARY_LIST_ITEMS]

    if not draft.get("review_status"):
        draft["review_status"] = REVIEW_STATUS

    overall_confidence = draft.get("overall_confidence")
    if not isinstance(overall_confidence, (int, float)) or isinstance(overall_confidence, bool):
        # The summary is a single advisory verdict: its confidence is derived from how much
        # reviewed context it could rest on, never authored by the model.
        draft["overall_confidence"] = _derive_overall_confidence(draft)
    else:
        draft["overall_confidence"] = float(overall_confidence)


def _derive_overall_confidence(draft: dict[str, Any]) -> float:
    populated = sum(1 for field in REQUIRED_LIST_FIELDS if draft.get(field))
    if not populated:
        return 0.0
    return round(min(0.9, 0.4 + 0.1 * populated), 2)


def _normalize_ambiguity_flags(value: Any) -> list[dict[str, str]]:
    """Coerce provider-supplied ambiguity flags into the {code, message} contract."""
    if not isinstance(value, list):
        return []

    normalized: list[dict[str, str]] = []
    for flag in value:
        if isinstance(flag, str):
            message = flag.strip()
            if message:
                normalized.append({"code": "provider_ambiguity", "message": message})
        elif isinstance(flag, dict):
            code = str(flag.get("code") or "provider_ambiguity").strip() or "provider_ambiguity"
            message = flag.get("message")
            if not isinstance(message, str) or not message.strip():
                message = str(flag.get("code") or "Ambiguity flagged by provider.")
            normalized.append({"code": code, "message": message.strip()})
        # Non-string, non-dict entries are dropped (treated as invalid).
    return normalized
