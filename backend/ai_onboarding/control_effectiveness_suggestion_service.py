from __future__ import annotations

from pathlib import Path
from typing import Any

from .control_effectiveness_suggestion_guardrails import (
    ControlEffectivenessSuggestionDraftValidationError,
    build_known_control_registry,
    resolve_known_control,
    validate_control_effectiveness_suggestion_guardrails,
)
from .control_effectiveness_suggestion_provider import (
    ControlEffectivenessSuggestionProviderError,
    get_control_effectiveness_suggestion_provider,
)
from .control_effectiveness_suggestion_serializers import (
    AiControlEffectivenessSuggestionDraftSerializer,
    COMPLIANCE_STATUS_CHOICES,
    DEFAULT_USER_LOCALE,
    EFFECTIVENESS_CHOICES,
    MAX_CONTROL_EFFECTIVENESS_SUGGESTIONS,
)


# Step 9A is advisory-only: the response carries no ids, no write flags, and no approval
# flags. Every suggestion stays at review_status 'pending_review'.
REVIEW_STATUS = "pending_review"

ALLOWED_SUGGESTION_KEYS = {
    "temporary_id",
    "framework_control_reference",
    "framework_control_code",
    "framework_control_title",
    "linked_requirement_assessment_reference",
    "linked_applied_control_reference",
    "linked_applied_control_title",
    "linked_finding_reference",
    "linked_finding_title",
    "suggested_effectiveness",
    "suggested_compliance_status",
    "evidence_summary",
    "gaps",
    "recommended_auditor_action",
    "rationale",
    "confidence",
    "review_status",
}

OPTIONAL_LINK_KEYS = (
    "framework_control_code",
    "linked_requirement_assessment_reference",
    "linked_applied_control_reference",
    "linked_applied_control_title",
    "linked_finding_reference",
    "linked_finding_title",
)

TEXT_SUGGESTION_KEYS = (
    "temporary_id",
    "framework_control_reference",
    "framework_control_title",
    "evidence_summary",
    "recommended_auditor_action",
    "rationale",
    *OPTIONAL_LINK_KEYS,
)

ENUM_KEYS = (
    ("suggested_effectiveness", EFFECTIVENESS_CHOICES),
    ("suggested_compliance_status", COMPLIANCE_STATUS_CHOICES),
)


class AiControlEffectivenessSuggestionService:
    def __init__(self, *, base_dir: str | None = None, provider=None):
        self.base_dir = base_dir or str(Path(__file__).resolve().parents[1])
        self.provider = provider

    def build_control_effectiveness_suggestion_draft(
        self, request_data: dict[str, Any]
    ) -> dict[str, Any]:
        normalized = _normalize_request_data(request_data)
        registry = build_known_control_registry(normalized)

        if not registry:
            # Nothing existing to judge: Step 9A refuses rather than inventing a control.
            return _finalize(_build_blocked_draft(), registry)

        provider = (
            self.provider
            if self.provider is not None
            else get_control_effectiveness_suggestion_provider()
        )

        if provider is None:
            draft = build_control_effectiveness_suggestion_fallback_draft(normalized)
            _annotate_provider_mode(
                draft,
                provider_mode="provider_not_configured_fallback",
                warning={
                    "code": "provider_not_configured_fallback",
                    "message": (
                        "No AI provider is configured; the advisory control effectiveness "
                        "draft was generated by the deterministic fallback."
                    ),
                    "affected_fields": ["control_effectiveness_suggestions"],
                    "needs_review": True,
                },
            )
        else:
            try:
                draft = provider.build_control_effectiveness_suggestion_draft(normalized)
                _annotate_provider_mode(draft, provider_mode="configured_local_provider")
            except ControlEffectivenessSuggestionProviderError as exc:
                if not exc.allow_fallback:
                    raise
                draft = build_control_effectiveness_suggestion_fallback_draft(normalized)
                _annotate_provider_mode(
                    draft,
                    provider_mode="local_provider_error_fallback",
                    warning={
                        "code": "local_provider_error_fallback",
                        "message": exc.detail,
                        "affected_fields": ["control_effectiveness_suggestions"],
                        "needs_review": True,
                    },
                )

        _enrich_draft(draft, registry)
        return _finalize(draft, registry)


def build_control_effectiveness_suggestion_draft(
    request_data: dict[str, Any],
    *,
    base_dir: str | None = None,
    provider=None,
) -> dict[str, Any]:
    service = AiControlEffectivenessSuggestionService(base_dir=base_dir, provider=provider)
    return service.build_control_effectiveness_suggestion_draft(request_data)


def _finalize(draft: dict[str, Any], registry: dict[str, dict[str, Any]]) -> dict[str, Any]:
    validate_control_effectiveness_suggestion_guardrails(draft, registry)

    serializer = AiControlEffectivenessSuggestionDraftSerializer(data=draft)
    if not serializer.is_valid():
        raise ControlEffectivenessSuggestionDraftValidationError(
            "ai_control_effectiveness_suggestion_draft_validation_failed",
            "Generated advisory control effectiveness draft did not pass contract validation.",
            serializer.errors,
        )

    validated_draft = serializer.data
    validate_control_effectiveness_suggestion_guardrails(validated_draft, registry)
    return validated_draft


def _build_blocked_draft() -> dict[str, Any]:
    return {
        "provider_mode": "control_context_missing_blocked",
        "overall_confidence": 0.0,
        "control_effectiveness_suggestions": [],
        "warnings": [
            {
                "code": "no_known_framework_controls",
                "message": (
                    "No framework control mappings and no requirement assessments were "
                    "supplied, so Step 9A produced no effectiveness suggestions. Framework "
                    "controls are never invented in this step."
                ),
                "affected_fields": ["framework_mappings", "requirement_assessments"],
                "needs_review": True,
            }
        ],
        "ambiguity_flags": [
            {
                "code": "no_known_framework_controls",
                "message": (
                    "Complete Step 7A/7B, or supply framework_mappings or "
                    "requirement_assessments, before Step 9A can suggest control "
                    "effectiveness."
                ),
            }
        ],
    }


# ---- Deterministic fallback ----------------------------------------------------------


def build_control_effectiveness_suggestion_fallback_draft(
    request_data: dict[str, Any],
) -> dict[str, Any]:
    """Deterministic advisory draft used when no local provider is available.

    It never reads or writes the database and never invents a framework control: every
    suggestion is anchored on a supplied mapping or requirement assessment. With no
    reviewed evidence it deliberately answers needs_more_evidence rather than guessing.
    """
    controls = _fallback_control_rows(request_data)
    evidence_items = request_data.get("evidence_requests") or []
    audit_questions = request_data.get("audit_questions") or []
    findings = request_data.get("preliminary_findings") or []
    applied_controls = request_data.get("applied_controls") or []

    primary_control = applied_controls[0] if applied_controls else {}
    primary_finding = findings[0] if findings else {}

    suggestions: list[dict[str, Any]] = []
    warnings: list[dict[str, Any]] = []

    for control in controls[:MAX_CONTROL_EFFECTIVENESS_SUGGESTIONS]:
        index = len(suggestions) + 1
        has_open_finding = bool(findings)
        # Without collected evidence nothing can be judged effective, and an open
        # preliminary finding is a gap rather than a compliance conclusion.
        effectiveness = "needs_more_evidence" if not has_open_finding else "partially_effective"
        compliance_status = (
            "needs_more_evidence" if not has_open_finding else "partially_compliant"
        )
        suggestions.append(
            {
                "temporary_id": f"effectiveness_{index}",
                "framework_control_reference": control.get("reference") or "",
                "framework_control_code": control.get("code") or "",
                "framework_control_title": control.get("title") or "",
                "linked_requirement_assessment_reference": (
                    control.get("requirement_assessment_reference") or ""
                ),
                "linked_applied_control_reference": primary_control.get("reference") or "",
                "linked_applied_control_title": primary_control.get("title") or "",
                "linked_finding_reference": primary_finding.get("reference") or "",
                "linked_finding_title": primary_finding.get("title") or "",
                "suggested_effectiveness": effectiveness,
                "suggested_compliance_status": compliance_status,
                "evidence_summary": _fallback_evidence_summary(evidence_items, audit_questions),
                "gaps": _fallback_gaps(findings, request_data.get("known_weaknesses") or []),
                "recommended_auditor_action": (
                    "Collect and review the outstanding evidence, then record the result on "
                    "the requirement assessment during human review."
                ),
                "rationale": (
                    f"Derived from the supplied framework control '{control.get('title')}' and "
                    "the reviewed onboarding context. This is an advisory judgement for human "
                    "review; no requirement assessment is updated by this step."
                ),
                "confidence": 0.6 if has_open_finding else 0.5,
                "review_status": REVIEW_STATUS,
            }
        )

    if not suggestions:
        warnings.append(
            {
                "code": "no_control_effectiveness_derived",
                "message": (
                    "The supplied framework mappings and requirement assessments contained no "
                    "readable control reference, so no effectiveness suggestion was drafted."
                ),
                "affected_fields": ["framework_mappings", "requirement_assessments"],
                "needs_review": True,
            }
        )

    return {
        "provider_mode": "provider_not_configured_fallback",
        "overall_confidence": 0.0,
        "control_effectiveness_suggestions": suggestions,
        "warnings": warnings,
        "ambiguity_flags": [],
    }


def _fallback_control_rows(request_data: dict[str, Any]) -> list[dict[str, Any]]:
    """Existing controls to judge, de-duplicated and in supplied order."""
    rows: list[dict[str, Any]] = []
    seen: set[str] = set()

    for mapping in request_data.get("framework_mappings") or []:
        reference = (mapping.get("reference") or mapping.get("code") or "").strip()
        title = (mapping.get("title") or "").strip()
        key = (reference or title).lower()
        if not key or key in seen:
            continue
        seen.add(key)
        rows.append(
            {
                "reference": reference or title,
                "code": mapping.get("code") or "",
                "title": title,
                "requirement_assessment_reference": (
                    mapping.get("requirement_assessment_reference") or ""
                ),
            }
        )

    for assessment in request_data.get("requirement_assessments") or []:
        reference = (
            assessment.get("framework_control_reference")
            or assessment.get("framework_control_code")
            or ""
        ).strip()
        title = (assessment.get("framework_control_title") or "").strip()
        key = (reference or title).lower()
        if not key or key in seen:
            continue
        seen.add(key)
        rows.append(
            {
                "reference": reference or title,
                "code": assessment.get("framework_control_code") or "",
                "title": title,
                "requirement_assessment_reference": assessment.get("reference") or "",
            }
        )

    return rows


def _fallback_evidence_summary(evidence_items, audit_questions) -> str:
    collected = [
        (item.get("title") or "").strip()
        for item in list(evidence_items)[:3]
        if (item.get("title") or "").strip()
    ]
    questions = [
        (item.get("title") or "").strip()
        for item in list(audit_questions)[:2]
        if (item.get("title") or "").strip()
    ]
    if not collected and not questions:
        return (
            "No evidence has been supplied for this control yet, so its operating "
            "effectiveness cannot be judged."
        )
    parts = []
    if collected:
        parts.append("Requested evidence: " + "; ".join(collected) + ".")
    if questions:
        parts.append("Open audit questions: " + "; ".join(questions) + ".")
    parts.append("None of it has been verified as collected and reviewed yet.")
    return " ".join(parts)


def _fallback_gaps(findings, known_weaknesses) -> list[str]:
    gaps: list[str] = []
    for finding in list(findings)[:3]:
        title = (finding.get("title") or "").strip()
        if title and title not in gaps:
            gaps.append(title[:500])
    for weakness in list(known_weaknesses)[:3]:
        trimmed = (weakness or "").strip()
        if trimmed and trimmed not in gaps:
            gaps.append(trimmed[:500])
    return gaps or ["Evidence confirming the control operates as described has not been reviewed."]


# ---- Normalization -------------------------------------------------------------------


def _normalize_request_data(request_data: dict[str, Any]) -> dict[str, Any]:
    normalized = dict(request_data)
    normalized["user_locale"] = normalized.get("user_locale") or DEFAULT_USER_LOCALE
    normalized["strict_mode"] = bool(normalized.get("strict_mode", True))
    normalized["known_weaknesses"] = list(normalized.get("known_weaknesses") or [])
    for field in (
        "framework_mappings",
        "requirement_assessments",
        "applied_controls",
        "evidence_requests",
        "audit_questions",
        "preliminary_findings",
        "remediation_actions",
        "risk_scenarios",
    ):
        normalized[field] = list(normalized.get(field) or [])
    normalized["folder_reference"] = normalized.get("folder_reference") or {}
    normalized["assessment_reference"] = normalized.get("assessment_reference") or {}
    return normalized


def _annotate_provider_mode(
    draft: dict[str, Any],
    *,
    provider_mode: str,
    warning: dict[str, Any] | None = None,
) -> None:
    draft["provider_mode"] = provider_mode
    if warning is not None:
        warnings = draft.setdefault("warnings", [])
        if not any(
            isinstance(item, dict) and item.get("code") == warning["code"] for item in warnings
        ):
            warnings.append(warning)


def _enrich_draft(draft: dict[str, Any], registry: dict[str, dict[str, Any]]) -> None:
    draft.setdefault("provider_mode", "configured_local_provider")
    draft.setdefault("warnings", [])
    draft["ambiguity_flags"] = _normalize_ambiguity_flags(draft.get("ambiguity_flags"))

    suggestions = draft.get("control_effectiveness_suggestions")
    if isinstance(suggestions, list):
        normalized = [
            _normalize_suggestion(index, suggestion, registry)
            if isinstance(suggestion, dict)
            else suggestion
            for index, suggestion in enumerate(suggestions, start=1)
        ]
        if len(normalized) > MAX_CONTROL_EFFECTIVENESS_SUGGESTIONS:
            _annotate_provider_mode(
                draft,
                provider_mode=draft["provider_mode"],
                warning={
                    "code": "control_effectiveness_suggestions_trimmed",
                    "message": (
                        f"Step 9A kept the first {MAX_CONTROL_EFFECTIVENESS_SUGGESTIONS} "
                        "advisory suggestions for review; "
                        f"{len(normalized) - MAX_CONTROL_EFFECTIVENESS_SUGGESTIONS} further "
                        "suggestions were trimmed."
                    ),
                    "affected_fields": ["control_effectiveness_suggestions"],
                    "needs_review": True,
                },
            )
        draft["control_effectiveness_suggestions"] = normalized[
            :MAX_CONTROL_EFFECTIVENESS_SUGGESTIONS
        ]

    _refresh_overall_confidence(draft)


def _normalize_suggestion(
    index: int, suggestion: dict[str, Any], registry: dict[str, dict[str, Any]]
) -> dict[str, Any]:
    """Fix harmless provider formatting and restore control-owned metadata.

    Whitespace, letter case on the enum fields, numeric strings for confidence, and the
    positional temporary_id are normalized. Blank framework control metadata is filled from
    the resolved supplied control so it can never be authored by the model. Missing or
    invalid substance (unknown control, unknown enum value, out-of-range confidence) is
    left untouched so the Step 9A guardrails reject it.
    """
    cleaned = {key: value for key, value in suggestion.items() if key in ALLOWED_SUGGESTION_KEYS}

    for key in TEXT_SUGGESTION_KEYS:
        value = cleaned.get(key)
        if isinstance(value, str):
            cleaned[key] = value.strip()

    if not cleaned.get("temporary_id"):
        cleaned["temporary_id"] = f"effectiveness_{index}"

    for key, choices in ENUM_KEYS:
        value = cleaned.get(key)
        if isinstance(value, str):
            lowered = value.strip().lower()
            cleaned[key] = lowered if lowered in choices else value.strip()

    confidence = cleaned.get("confidence")
    if isinstance(confidence, str):
        try:
            cleaned["confidence"] = float(confidence.strip())
        except ValueError:
            pass

    gaps = cleaned.get("gaps")
    if isinstance(gaps, list):
        cleaned["gaps"] = [entry.strip() if isinstance(entry, str) else entry for entry in gaps]

    control = resolve_known_control(cleaned, registry)
    if control is not None:
        if not cleaned.get("framework_control_reference"):
            cleaned["framework_control_reference"] = (
                control.get("reference") or control.get("code") or control.get("title") or ""
            )
        if not cleaned.get("framework_control_code"):
            cleaned["framework_control_code"] = control.get("code") or ""
        if not cleaned.get("framework_control_title"):
            cleaned["framework_control_title"] = control.get("title") or ""
        if not cleaned.get("linked_requirement_assessment_reference"):
            cleaned["linked_requirement_assessment_reference"] = (
                control.get("requirement_assessment_reference") or ""
            )

    for key in (*OPTIONAL_LINK_KEYS, "evidence_summary", "recommended_auditor_action"):
        if not isinstance(cleaned.get(key), str):
            cleaned[key] = ""

    if not cleaned.get("review_status"):
        cleaned["review_status"] = REVIEW_STATUS

    return cleaned


def _normalize_ambiguity_flags(value: Any) -> list[dict[str, str]]:
    """Coerce provider-supplied ambiguity flags into the {code, message} contract."""
    if not isinstance(value, list):
        return []

    normalized: list[dict[str, str]] = []
    for flag in value:
        if isinstance(flag, str):
            message = flag.strip()
            if message:
                normalized.append({"code": "provider_ambiguity", "message": message})
        elif isinstance(flag, dict):
            code = str(flag.get("code") or "provider_ambiguity").strip() or "provider_ambiguity"
            message = flag.get("message")
            if not isinstance(message, str) or not message.strip():
                message = str(flag.get("code") or "Ambiguity flagged by provider.")
            normalized.append({"code": code, "message": message.strip()})
        # Non-string, non-dict entries are dropped (treated as invalid).
    return normalized


def _refresh_overall_confidence(draft: dict[str, Any]) -> None:
    scores: list[float] = []
    for suggestion in draft.get("control_effectiveness_suggestions") or []:
        if not isinstance(suggestion, dict):
            continue
        score = suggestion.get("confidence")
        if isinstance(score, (int, float)) and not isinstance(score, bool):
            if 0.0 <= float(score) <= 1.0:
                scores.append(float(score))
    draft["overall_confidence"] = round(sum(scores) / len(scores), 2) if scores else 0.0
