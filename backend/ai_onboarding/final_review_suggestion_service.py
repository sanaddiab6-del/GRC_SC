from __future__ import annotations

from pathlib import Path
from typing import Any

from .final_review_suggestion_guardrails import (
    FinalReviewSuggestionDraftValidationError,
    REQUIRED_LIST_FIELDS,
    validate_final_review_suggestion_guardrails,
)
from .final_review_suggestion_provider import (
    FinalReviewSuggestionProviderError,
    get_final_review_suggestion_provider,
)
from .final_review_suggestion_serializers import (
    AiFinalReviewSuggestionDraftSerializer,
    DEFAULT_USER_LOCALE,
    DEMO_READINESS_STATUS_CHOICES,
    MAX_SUMMARY_LIST_ITEMS,
)


# Step 12A is advisory-only: the response carries no ids, no write flags, and no approval
# flags. The summary always stays at review_status 'pending_review'.
REVIEW_STATUS = "pending_review"

MAX_LIST_ENTRY_LENGTH = 500

ALLOWED_DRAFT_KEYS = {
    "provider_mode",
    "overall_confidence",
    "completion_summary",
    *REQUIRED_LIST_FIELDS,
    "demo_readiness_status",
    "warnings",
    "ambiguity_flags",
    "review_status",
}

# Step outcome statuses that mean the step actually produced a reviewed result.
_COMPLETED_STATUSES = {
    "completed",
    "completed_with_warnings",
    "created",
    "reused_only",
    "validated",
    "validated_with_warnings",
    "done",
    "ok",
}

_BLOCKED_STATUSES = {"blocked", "failed", "error"}


class AiFinalReviewSuggestionService:
    def __init__(self, *, base_dir: str | None = None, provider=None):
        self.base_dir = base_dir or str(Path(__file__).resolve().parents[1])
        self.provider = provider

    def build_final_review_suggestion_draft(
        self, request_data: dict[str, Any]
    ) -> dict[str, Any]:
        normalized = _normalize_request_data(request_data)

        if not _has_final_review_context(normalized):
            # Nothing recorded to review: Step 12A refuses rather than inventing a completion
            # story.
            return _finalize(_build_blocked_draft())

        provider = (
            self.provider
            if self.provider is not None
            else get_final_review_suggestion_provider()
        )

        if provider is None:
            draft = build_final_review_suggestion_fallback_draft(normalized)
            _annotate_provider_mode(
                draft,
                provider_mode="provider_not_configured_fallback",
                warning={
                    "code": "provider_not_configured_fallback",
                    "message": (
                        "No AI provider is configured; the advisory final review summary was "
                        "generated by the deterministic fallback."
                    ),
                    "affected_fields": ["completion_summary", "demo_readiness_status"],
                    "needs_review": True,
                },
            )
        else:
            try:
                draft = provider.build_final_review_suggestion_draft(normalized)
                _annotate_provider_mode(draft, provider_mode="configured_local_provider")
            except FinalReviewSuggestionProviderError as exc:
                if not exc.allow_fallback:
                    raise
                draft = build_final_review_suggestion_fallback_draft(normalized)
                _annotate_provider_mode(
                    draft,
                    provider_mode="local_provider_error_fallback",
                    warning={
                        "code": "local_provider_error_fallback",
                        "message": exc.detail,
                        "affected_fields": ["completion_summary", "demo_readiness_status"],
                        "needs_review": True,
                    },
                )

        _enrich_draft(draft)
        return _finalize(draft)


def build_final_review_suggestion_draft(
    request_data: dict[str, Any],
    *,
    base_dir: str | None = None,
    provider=None,
) -> dict[str, Any]:
    service = AiFinalReviewSuggestionService(base_dir=base_dir, provider=provider)
    return service.build_final_review_suggestion_draft(request_data)


def _finalize(draft: dict[str, Any]) -> dict[str, Any]:
    validate_final_review_suggestion_guardrails(draft)

    serializer = AiFinalReviewSuggestionDraftSerializer(data=draft)
    if not serializer.is_valid():
        raise FinalReviewSuggestionDraftValidationError(
            "ai_final_review_suggestion_draft_validation_failed",
            "Generated advisory final review draft did not pass contract validation.",
            serializer.errors,
        )

    validated_draft = serializer.data
    validate_final_review_suggestion_guardrails(validated_draft)
    return validated_draft


def _has_final_review_context(request_data: dict[str, Any]) -> bool:
    return bool(
        request_data.get("step_outcomes")
        or request_data.get("created_records")
        or request_data.get("reused_records")
        or request_data.get("blocked_items")
        or request_data.get("outstanding_items")
    )


def _build_blocked_draft() -> dict[str, Any]:
    return {
        "provider_mode": "final_review_context_missing_blocked",
        "overall_confidence": 0.0,
        "completion_summary": (
            "No onboarding step outcomes or records were supplied, so the flow cannot be "
            "reviewed. Nothing is asserted about what was completed."
        ),
        "completed_steps": [],
        "incomplete_steps": [],
        "created_or_reused_records_summary": [],
        "blocked_items": [],
        "human_review_required": [
            "Supply the onboarding step outcomes before relying on this summary."
        ],
        "recommended_next_steps": [
            "Run the earlier onboarding steps, then run Step 12A again."
        ],
        "demo_readiness_status": "blocked",
        "warnings": [
            {
                "code": "no_final_review_input_context",
                "message": (
                    "No step outcomes, created records, reused records, blocked items, or "
                    "outstanding items were supplied, so Step 12A produced no review summary."
                ),
                "affected_fields": [
                    "step_outcomes",
                    "created_records",
                    "reused_records",
                    "blocked_items",
                    "outstanding_items",
                ],
                "needs_review": True,
            }
        ],
        "ambiguity_flags": [
            {
                "code": "no_final_review_input_context",
                "message": "Complete Steps 1-11B before Step 12A can summarize the flow.",
            }
        ],
        "review_status": REVIEW_STATUS,
    }


# ---- Deterministic fallback ----------------------------------------------------------


def build_final_review_suggestion_fallback_draft(
    request_data: dict[str, Any],
) -> dict[str, Any]:
    """Deterministic advisory summary used when no local provider is available.

    It never reads or writes the database: every statement is derived from the readable
    request context only, and it never asserts that the workflow or audit is complete.
    """
    step_outcomes = request_data.get("step_outcomes") or []
    created_records = request_data.get("created_records") or []
    reused_records = request_data.get("reused_records") or []
    blocked_items = list(request_data.get("blocked_items") or [])
    outstanding_items = list(request_data.get("outstanding_items") or [])

    completed_steps: list[str] = []
    incomplete_steps: list[str] = []

    for outcome in step_outcomes:
        if not isinstance(outcome, dict):
            continue
        step = (outcome.get("step") or "").strip()
        if not step:
            continue
        status = (outcome.get("status") or "").strip().lower()
        label = f"{step}: {status}" if status else step
        if status in _COMPLETED_STATUSES:
            completed_steps.append(label[:MAX_LIST_ENTRY_LENGTH])
        else:
            incomplete_steps.append(label[:MAX_LIST_ENTRY_LENGTH])
            if status in _BLOCKED_STATUSES:
                detail = (outcome.get("detail") or "").strip()
                blocked_items.append((detail or label)[:MAX_LIST_ENTRY_LENGTH])

    records_summary = [
        *(
            f"Created {(record.get('record_type') or 'record')}: {record.get('name')}"
            for record in created_records
            if isinstance(record, dict) and (record.get("name") or "").strip()
        ),
        *(
            f"Reused {(record.get('record_type') or 'record')}: {record.get('name')}"
            for record in reused_records
            if isinstance(record, dict) and (record.get("name") or "").strip()
        ),
    ]

    human_review_required = [
        "Every AI suggestion recorded during onboarding is advisory and needs owner confirmation.",
        "Preliminary findings must be confirmed or dismissed by their owners.",
        "Risk scenarios must be rated on the platform risk matrix by a human.",
        "Recorded requirement results must be reviewed before any audit conclusion is drawn.",
        *outstanding_items,
    ]

    recommended_next_steps = [
        "Review the saved report draft with the accountable auditor.",
        "Resolve every blocked item listed above.",
        "Collect the outstanding evidence and close the open audit questions.",
    ]

    demo_readiness_status = _fallback_status(
        completed_count=len(completed_steps),
        incomplete_count=len(incomplete_steps),
        blocked_count=len(blocked_items),
    )

    completion_summary = (
        f"The onboarding flow recorded {len(completed_steps)} completed step outcome(s) and "
        f"{len(incomplete_steps)} outcome(s) that are not complete, with "
        f"{len(created_records)} created and {len(reused_records)} reused record(s). "
        f"{len(blocked_items)} item(s) are blocked. This summary is a review aid: it does "
        "not mark the workflow, the assessment, or the audit as finished."
    )

    return {
        "provider_mode": "provider_not_configured_fallback",
        "overall_confidence": 0.0,
        "completion_summary": completion_summary,
        "completed_steps": completed_steps,
        "incomplete_steps": incomplete_steps,
        "created_or_reused_records_summary": records_summary,
        "blocked_items": blocked_items,
        "human_review_required": human_review_required,
        "recommended_next_steps": recommended_next_steps,
        "demo_readiness_status": demo_readiness_status,
        "warnings": [],
        "ambiguity_flags": [],
        "review_status": REVIEW_STATUS,
    }


def _fallback_status(*, completed_count: int, incomplete_count: int, blocked_count: int) -> str:
    """Readable advisory demo-readiness label. Never a platform status."""
    if blocked_count:
        return "blocked"
    if not completed_count:
        return "not_ready"
    if incomplete_count:
        return "partially_ready"
    return "ready"


# ---- Normalization -------------------------------------------------------------------


def _normalize_request_data(request_data: dict[str, Any]) -> dict[str, Any]:
    normalized = dict(request_data)
    normalized["user_locale"] = normalized.get("user_locale") or DEFAULT_USER_LOCALE
    normalized["strict_mode"] = bool(normalized.get("strict_mode", True))
    for field in ("blocked_items", "outstanding_items"):
        normalized[field] = list(normalized.get(field) or [])
    for field in ("step_outcomes", "created_records", "reused_records"):
        normalized[field] = list(normalized.get(field) or [])
    normalized["folder_reference"] = normalized.get("folder_reference") or {}
    normalized["assessment_reference"] = normalized.get("assessment_reference") or {}
    return normalized


def _annotate_provider_mode(
    draft: dict[str, Any],
    *,
    provider_mode: str,
    warning: dict[str, Any] | None = None,
) -> None:
    draft["provider_mode"] = provider_mode
    if warning is not None:
        warnings = draft.setdefault("warnings", [])
        if not any(
            isinstance(item, dict) and item.get("code") == warning["code"] for item in warnings
        ):
            warnings.append(warning)


def _enrich_draft(draft: dict[str, Any]) -> None:
    """Fix harmless provider formatting only.

    Whitespace, unknown keys, letter case on demo_readiness_status, and list entry trimming
    are normalized. Missing or invalid substance (unknown status, non-string list entries)
    is left untouched so the Step 12A guardrails reject it.
    """
    for key in list(draft.keys()):
        if key not in ALLOWED_DRAFT_KEYS:
            del draft[key]

    draft.setdefault("provider_mode", "configured_local_provider")
    draft.setdefault("warnings", [])
    draft["ambiguity_flags"] = _normalize_ambiguity_flags(draft.get("ambiguity_flags"))

    status = draft.get("demo_readiness_status")
    if isinstance(status, str):
        lowered = status.strip().lower().replace(" ", "_")
        draft["demo_readiness_status"] = (
            lowered if lowered in DEMO_READINESS_STATUS_CHOICES else status.strip()
        )

    completion_summary = draft.get("completion_summary")
    if isinstance(completion_summary, str):
        draft["completion_summary"] = completion_summary.strip()

    for field in REQUIRED_LIST_FIELDS:
        value = draft.get(field)
        if value is None:
            draft[field] = []
            continue
        if not isinstance(value, list):
            continue
        trimmed = [
            entry.strip()[:MAX_LIST_ENTRY_LENGTH] if isinstance(entry, str) else entry
            for entry in value
        ]
        if len(trimmed) > MAX_SUMMARY_LIST_ITEMS:
            _annotate_provider_mode(
                draft,
                provider_mode=draft["provider_mode"],
                warning={
                    "code": "final_review_list_trimmed",
                    "message": (
                        f"Step 12A kept the first {MAX_SUMMARY_LIST_ITEMS} entries of {field} "
                        "for review; further entries were trimmed."
                    ),
                    "affected_fields": [field],
                    "needs_review": True,
                },
            )
        draft[field] = trimmed[:MAX_SUMMARY_LIST_ITEMS]

    if not draft.get("review_status"):
        draft["review_status"] = REVIEW_STATUS

    overall_confidence = draft.get("overall_confidence")
    if not isinstance(overall_confidence, (int, float)) or isinstance(overall_confidence, bool):
        # The summary is a single advisory verdict: its confidence is derived from how much
        # recorded flow state it could rest on, never authored by the model.
        draft["overall_confidence"] = _derive_overall_confidence(draft)
    else:
        draft["overall_confidence"] = float(overall_confidence)


def _derive_overall_confidence(draft: dict[str, Any]) -> float:
    populated = sum(1 for field in REQUIRED_LIST_FIELDS if draft.get(field))
    if not populated:
        return 0.0
    return round(min(0.9, 0.4 + 0.1 * populated), 2)


def _normalize_ambiguity_flags(value: Any) -> list[dict[str, str]]:
    """Coerce provider-supplied ambiguity flags into the {code, message} contract."""
    if not isinstance(value, list):
        return []

    normalized: list[dict[str, str]] = []
    for flag in value:
        if isinstance(flag, str):
            message = flag.strip()
            if message:
                normalized.append({"code": "provider_ambiguity", "message": message})
        elif isinstance(flag, dict):
            code = str(flag.get("code") or "provider_ambiguity").strip() or "provider_ambiguity"
            message = flag.get("message")
            if not isinstance(message, str) or not message.strip():
                message = str(flag.get("code") or "Ambiguity flagged by provider.")
            normalized.append({"code": code, "message": message.strip()})
        # Non-string, non-dict entries are dropped (treated as invalid).
    return normalized
